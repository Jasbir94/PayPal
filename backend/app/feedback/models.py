"""Closed vocabularies for payment behavior and independently adjudicated outcomes."""
from enum import StrEnum


class UserAction(StrEnum):
    PAYMENT_ALLOWED = 'PAYMENT_ALLOWED'
    PAYMENT_COMPLETED = 'PAYMENT_COMPLETED'
    USER_CANCELLED = 'USER_CANCELLED'
    USER_CONTINUED_AFTER_WARNING = 'USER_CONTINUED_AFTER_WARNING'
    USER_VERIFIED_AND_CONTINUED = 'USER_VERIFIED_AND_CONTINUED'
    PAYMENT_HELD = 'PAYMENT_HELD'
    MANUAL_REVIEW_REQUESTED = 'MANUAL_REVIEW_REQUESTED'


class FraudLabel(StrEnum):
    UNKNOWN = 'UNKNOWN'
    LEGITIMATE = 'LEGITIMATE'
    CONFIRMED_SCAM = 'CONFIRMED_SCAM'
    CONFIRMED_MULE = 'CONFIRMED_MULE'
    DISPUTED = 'DISPUTED'
    UNDER_REVIEW = 'UNDER_REVIEW'


class LabelSource(StrEnum):
    SYNTHETIC_GROUND_TRUTH = 'SYNTHETIC_GROUND_TRUTH'
    USER_REPORT = 'USER_REPORT'
    ANALYST_CONFIRMED = 'ANALYST_CONFIRMED'
    CHARGEBACK = 'CHARGEBACK'
    RECIPIENT_INVESTIGATION = 'RECIPIENT_INVESTIGATION'
    EXTERNAL_CONFIRMED_SIGNAL = 'EXTERNAL_CONFIRMED_SIGNAL'
    UNKNOWN = 'UNKNOWN'


TRAINABLE_LABELS = {FraudLabel.LEGITIMATE, FraudLabel.CONFIRMED_SCAM, FraudLabel.CONFIRMED_MULE}
